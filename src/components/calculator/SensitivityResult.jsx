import { useEffect, useState } from 'react'
import { Clipboard } from 'lucide-react'

const MAX_SENSITIVITY = 200

const SETTINGS = [
  { key: 'general', label: 'General', color: '#00F6FF' },
  { key: 'redDot', label: 'Red Dot', color: '#FF4444' },
  { key: 'x2Scope', label: '2x Scope', color: '#8B5CF6' },
  { key: 'x4Scope', label: '4x Scope', color: '#F59E0B' },
  { key: 'sniper', label: 'Sniper', color: '#10B981' },
  { key: 'freeLook', label: 'Free Look', color: '#EC4899' },
]

function buildCopyText(result) {
  return `⚙️ HAFYN X — My Free Fire Sensitivity Settings
━━━━━━━━━━━━━━━━━━━━
🎯 General:      ${result.general}
🔴 Red Dot:      ${result.redDot}
🔭 2x Scope:     ${result.x2Scope}
🔭 4x Scope:     ${result.x4Scope}
🎯 Sniper:       ${result.sniper}
👁️ Free Look:    ${result.freeLook}
━━━━━━━━━━━━━━━━━━━━
${result.closestPro ? `Style: ${result.closestPro}\n` : ''}Generated by HAFYN X
hafynx.com`
}

function SensitivityCard({ setting, value, index, animateBars }) {
  const barWidth = (value / MAX_SENSITIVITY) * 100

  return (
    <div
      className="animate-fadeInUp relative overflow-hidden rounded-2xl border border-white/[0.06] px-4 py-5 text-center opacity-0"
      style={{
        background: 'rgba(10,11,20,0.9)',
        animationDelay: `${0.1 + index * 0.1}s`,
      }}
    >
      <div
        className="absolute left-0 right-0 top-0 h-0.5"
        style={{
          background: `linear-gradient(180deg, ${setting.color}33 0%, transparent 100%)`,
          boxShadow: `0 0 8px ${setting.color}40`,
        }}
      />
      <p
        className="mb-2 text-[11px] font-medium uppercase tracking-widest text-[#64748b]"
      >
        {setting.label}
      </p>
      <p
        className="text-[clamp(32px,6vw,48px)] font-black leading-none"
        style={{
          background: 'linear-gradient(135deg, #ffffff, #00F6FF)',
          WebkitBackgroundClip: 'text',
          WebkitTextFillColor: 'transparent',
          backgroundClip: 'text',
        }}
      >
        {value}
      </p>
      <div className="mt-3 h-[3px] overflow-hidden rounded-full bg-white/5">
        <div
          className="h-full rounded-full transition-[width] duration-1000 ease-out"
          style={{
            width: animateBars ? `${barWidth}%` : '0%',
            background: `linear-gradient(90deg, ${setting.color}, #0044FF)`,
          }}
        />
      </div>
    </div>
  )
}

function AISkeleton() {
  return (
    <div className="mt-3 space-y-3">
      <p className="text-xs text-[#64748b]">AI is analyzing your profile...</p>
      <div className="h-3 animate-pulse rounded bg-white/10" />
      <div className="h-3 w-4/5 animate-pulse rounded bg-white/10" />
      <div className="h-3 w-3/5 animate-pulse rounded bg-white/10" />
    </div>
  )
}

export default function SensitivityResult({ result }) {
  const [copied, setCopied] = useState(false)
  const [animateBars, setAnimateBars] = useState(false)

  useEffect(() => {
    setCopied(false)
    setAnimateBars(false)
    const t = requestAnimationFrame(() => {
      setAnimateBars(true)
    })
    return () => cancelAnimationFrame(t)
  }, [result])

  if (!result) return null

  async function handleCopy() {
    try {
      await navigator.clipboard.writeText(buildCopyText(result))
      setCopied(true)
      setTimeout(() => setCopied(false), 2000)
    } catch {
      setCopied(false)
    }
  }

  return (
    <div className="space-y-4 animate-fadeIn">
      <div className="animate-scaleIn text-center opacity-0">
        <div
          className="mx-auto mb-4 flex h-16 w-16 items-center justify-center rounded-full text-3xl"
          style={{
            background: 'rgba(0,246,255,0.1)',
            border: '1px solid rgba(0,246,255,0.3)',
            boxShadow: '0 0 30px rgba(0,246,255,0.2)',
          }}
        >
          ✓
        </div>
        <h2 className="text-2xl font-extrabold text-white md:text-3xl">
          ✦ Your Settings Are Ready
        </h2>
        <p className="mt-2 text-sm text-[#64748b]">
          Calibrated to your exact device and playstyle
        </p>
      </div>

      <div className="grid grid-cols-2 gap-3 md:grid-cols-3">
        {SETTINGS.map((setting, index) => (
          <SensitivityCard
            key={setting.key}
            setting={setting}
            value={result[setting.key]}
            index={index}
            animateBars={animateBars}
          />
        ))}
      </div>

      <button
        type="button"
        onClick={handleCopy}
        className={`flex w-full items-center justify-center gap-2 rounded-xl border px-4 py-3.5 text-sm font-semibold transition-all duration-200 ${
          copied
            ? 'border-[#00F6FF] bg-[#00F6FF]/10 text-[#00F6FF]'
            : 'border-white/10 bg-white/[0.04] text-white hover:border-[#00F6FF] hover:text-[#00F6FF]'
        }`}
      >
        {copied ? (
          '✓ Copied to Clipboard!'
        ) : (
          <>
            <Clipboard className="h-4 w-4" />
            Copy All Settings
          </>
        )}
      </button>

      {result.closestPro && (
        <div
          className="animate-scaleIn mt-4 rounded-2xl border border-[#00F6FF]/15 p-5 opacity-0"
          style={{
            background:
              'linear-gradient(135deg, rgba(0,246,255,0.05), rgba(0,68,255,0.05))',
          }}
        >
          <p className="text-[11px] font-semibold uppercase tracking-widest text-[#00F6FF]">
            Your Style Matches
          </p>
          <p className="mt-2 text-[22px] font-extrabold text-white">
            {result.closestPro}
          </p>
          <p className="mt-1 text-sm text-[#64748b]">
            AI matched your profile to the closest pro playstyle
          </p>
        </div>
      )}

      <div
        className="mt-3 rounded-r-xl border-l-[3px] border-[#00F6FF] p-5"
        style={{ background: 'rgba(0,246,255,0.03)' }}
      >
        <p className="mb-2 text-[11px] font-semibold uppercase tracking-widest text-[#00F6FF]">
          🤖 AI COACH
        </p>
        {result.analysis ? (
          <p className="text-sm leading-relaxed text-white">{result.analysis}</p>
        ) : (
          <AISkeleton />
        )}
      </div>

      {result.tips && (
        <div
          className="mt-3 rounded-r-xl border-l-[3px] border-[#F59E0B] p-5"
          style={{ background: 'rgba(245,158,11,0.03)' }}
        >
          <p className="mb-2 text-[11px] font-semibold uppercase tracking-widest text-[#F59E0B]">
            💡 PRO TIPS
          </p>
          <p className="text-sm leading-relaxed text-[#94A3B8]">{result.tips}</p>
        </div>
      )}
    </div>
  )
}
