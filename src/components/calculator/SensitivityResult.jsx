import { useEffect, useState } from 'react'

const MAX_SENSITIVITY = 200

const SETTINGS = [
  { key: 'general', label: 'General Sensitivity' },
  { key: 'redDot', label: 'Red Dot' },
  { key: 'x2Scope', label: '2x Scope' },
  { key: 'x4Scope', label: '4x Scope' },
  { key: 'sniper', label: 'Sniper Scope' },
  { key: 'freeLook', label: 'Free Look' },
]

function buildCopyText(result) {
  return `⚙️ HAFYN X — My Free Fire Sensitivity Settings
━━━━━━━━━━━━━━━━━━━━
🎯 General:      ${result.general}
🔴 Red Dot:      ${result.redDot}
🔭 2x Scope:     ${result.x2Scope}
🔭 4x Scope:     ${result.x4Scope}
🎯 Sniper:       ${result.sniper}
👁️ Free Look:    ${result.freeLook}
━━━━━━━━━━━━━━━━━━━━
${result.closestPro ? `Style: ${result.closestPro}\n` : ''}Generated by HAFYN X
hafynx.com`
}

function LoadingSkeleton() {
  return (
    <div className="space-y-5">
      <div className="text-center">
        <p className="text-lg font-semibold text-white">
          🤖 AI is analyzing your profile
          <span className="inline-flex w-8 justify-start">
            <span className="animate-pulse">.</span>
            <span className="animate-pulse [animation-delay:150ms]">.</span>
            <span className="animate-pulse [animation-delay:300ms]">.</span>
          </span>
        </p>
        <p className="mt-2 text-sm text-zinc-500">
          Matching you with pro player data...
        </p>
      </div>

      <div className="grid grid-cols-2 gap-3 sm:grid-cols-3">
        {Array.from({ length: 6 }).map((_, i) => (
          <div
            key={i}
            className="animate-pulse rounded-xl border border-brand-border bg-brand-card p-4"
          >
            <div className="mb-3 h-3 w-16 rounded bg-zinc-800" />
            <div className="mb-2 h-8 w-12 rounded bg-zinc-700" />
            <div className="h-1.5 w-full rounded-full bg-zinc-800" />
          </div>
        ))}
      </div>

      <div className="animate-pulse space-y-3">
        <div className="h-20 rounded-xl border border-brand-border bg-brand-card" />
        <div className="h-24 rounded-xl border border-brand-border bg-brand-card" />
        <div className="h-20 rounded-xl border border-brand-border bg-brand-card" />
      </div>
    </div>
  )
}

export default function SensitivityResult({ result, loading = false }) {
  const [copied, setCopied] = useState(false)

  useEffect(() => {
    setCopied(false)
  }, [result])

  if (loading) {
    return <LoadingSkeleton />
  }

  if (!result) return null

  async function handleCopy() {
    try {
      await navigator.clipboard.writeText(buildCopyText(result))
      setCopied(true)
      setTimeout(() => setCopied(false), 2000)
    } catch {
      setCopied(false)
    }
  }

  return (
    <div className="space-y-5">
      <h2 className="text-center text-xl font-bold text-white sm:text-2xl">
        Your Perfect Settings ✅
      </h2>

      <div className="grid grid-cols-2 gap-3 sm:grid-cols-3">
        {SETTINGS.map(({ key, label }) => {
          const value = result[key]
          const barWidth = (value / MAX_SENSITIVITY) * 100

          return (
            <div
              key={key}
              className="rounded-xl border border-brand-border bg-brand-card p-3 sm:p-4"
            >
              <p className="text-xs text-zinc-400">{label}</p>
              <p className="mt-1 text-2xl font-bold text-brand-yellow sm:text-3xl">
                {value}
              </p>
              <p className="text-[10px] text-zinc-500">out of 200</p>
              <div className="mt-2 h-1.5 w-full overflow-hidden rounded-full bg-brand-dark">
                <div
                  className="h-full rounded-full bg-brand-yellow"
                  style={{ width: `${barWidth}%` }}
                />
              </div>
            </div>
          )
        })}
      </div>

      <button
        type="button"
        onClick={handleCopy}
        className="w-full rounded-xl border border-brand-yellow py-3 text-sm font-semibold text-brand-yellow hover:bg-brand-yellow hover:text-black"
      >
        {copied ? 'Copied! ✅' : 'Copy All Settings'}
      </button>

      {result.closestPro && (
        <div className="rounded-xl border border-brand-border bg-brand-card p-4">
          <p className="text-xs font-semibold uppercase tracking-wider text-zinc-500">
            Your Style Matches
          </p>
          <p className="mt-2 text-base font-bold text-[#00D4FF]">
            {result.closestPro}
          </p>
          <p className="mt-1 text-xs text-zinc-400">
            AI matched your profile to the closest pro playstyle
          </p>
        </div>
      )}

      {result.analysis && (
        <div className="rounded-xl border border-brand-border border-l-4 border-l-[#00D4FF] bg-[#111111] p-4">
          <p className="text-sm font-semibold text-[#00D4FF]">
            🤖 AI Coach Says
          </p>
          <p className="mt-2 text-sm leading-relaxed text-zinc-300">
            {result.analysis}
          </p>
        </div>
      )}

      {result.tips && (
        <div className="rounded-xl border border-brand-border border-l-4 border-l-brand-yellow bg-brand-card p-4">
          <p className="text-sm font-semibold text-brand-yellow">
            💡 Adjustment Tips
          </p>
          <p className="mt-2 text-sm leading-relaxed text-zinc-300">
            {result.tips}
          </p>
        </div>
      )}
    </div>
  )
}
